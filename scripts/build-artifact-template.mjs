#!/usr/bin/env node
/* Builds the standalone calibrated-artifacts skill from the other three:
   - inlines the CSS and JS into assets/template.html
   - writes the kit on its own (assets/calibrated-inline.css / .js) for pages that don't start from the template
   - copies the reference docs it needs, so the skill works without the others installed.
   Run before each release:  node scripts/build-artifact-template.mjs */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const out = join(root, 'skills/calibrated-artifacts');

const css = [
  'skills/calibrated-tokens/assets/calibrated.css',
  'skills/calibrated-components/assets/calibrated-components.css',
].map(read).join('\n');

const js = [
  'skills/calibrated-figures/assets/calibrated-figures.js',
  'skills/calibrated-figures/assets/calibrated-recipes.js',
  'skills/calibrated-components/assets/calibrated-components.js',
].map(read).join('\n');

const version = JSON.parse(read('.claude-plugin/plugin.json')).version;
const stamp = `/* calibrated ${version} · generated by scripts/build-artifact-template.mjs. Edit the sources, not this block. */\n`;

let tpl = read('scripts/artifact-template.src.html');
for (const marker of ['/* @inline-css */', '/* @inline-js */']) {
  if (!tpl.includes(marker)) throw new Error(`template is missing ${marker}`);
}
if (js.includes('</script')) throw new Error('inlined JS contains </script');
tpl = tpl.replace('/* @inline-css */', () => stamp + css).replace('/* @inline-js */', () => stamp + js);

mkdirSync(join(out, 'assets'), { recursive: true });
mkdirSync(join(out, 'references'), { recursive: true });
writeFileSync(join(out, 'assets/template.html'), tpl);
writeFileSync(join(out, 'assets/calibrated-inline.css'), stamp + css);
writeFileSync(join(out, 'assets/calibrated-inline.js'), stamp + js);

const docs = {
  'skills/calibrated-tokens/references/theming.md': 'theming.md',
  'skills/calibrated-figures/references/marks.md': 'marks.md',
  'skills/calibrated-figures/references/recipes.md': 'recipes.md',
  'skills/calibrated-figures/references/drawing-quality.md': 'drawing-quality.md',
  'skills/calibrated-components/references/catalog.md': 'catalog.md',
  'skills/calibrated-components/references/ux-rules.md': 'ux-rules.md',
};
for (const [src, dst] of Object.entries(docs)) {
  writeFileSync(join(out, 'references', dst), `<!-- copied from ${src} by scripts/build-artifact-template.mjs -->\n` + read(src));
}

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(1) + ' KB';
console.log(`template.html ${kb(tpl)} · inline css ${kb(css)} · inline js ${kb(js)} · ${Object.keys(docs).length} references`);
